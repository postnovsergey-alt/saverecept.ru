def get_or_create_demo_user(db) -> User:
    user = auth.get_by_email(db, DEMO_EMAIL)
    if user:
        return user
    return auth.create_user(db, DEMO_EMAIL, DEMO_PASSWORD, display_name="Демо")


def main() -> None:
    init_db()
    db = SessionLocal()
    user = get_or_create_demo_user(db)
    added = 0
    for title, category, minutes, servings, domain, ingredients, steps in DEMO:
        url = f"https://{domain}/demo/{abs(hash(title)) % 100000}"
        if service.find_by_source(db, user.id, url):
            continue
        parsed = ParsedRecipe(
            title=title,
            description="Демонстрационный рецепт — можно удалить.",
            ingredients=[parse_ingredient_line(x) for x in ingredients],
            steps=steps,
            images=[],
            total_minutes=minutes,
            servings=servings,
            category=category,
            category_confidence=0.9,
            source_url=url,
            source_key=url_key(url),
            source_domain=domain,
            parse_method="demo",
        )
        service.save_parsed(db, user, parsed, added_from="web", added_by="демо")
        added += 1
    total = service.total_count(db, user.id)
    db.close()
    print(f"Добавлено демо-рецептов: {added}. У пользователя {DEMO_EMAIL}: {total}.")
    print(f"Логин: {DEMO_EMAIL}  Пароль: {DEMO_PASSWORD}")


if __name__ == "__main__":
    main()
